"""Generate constellation/data/jchronologer_models.json from an installed JChronologer jar.

JChronologer is EncyclopeDIA's library predictor: a jar of TorchScript
models (Chronologer for retention time, Cartographer for fragment
intensities, Electrician for charge states, Sculptor for CCS, Scout for
all four at once), each beside a ``.preprocessing.json`` that says how a
peptide becomes the model's tokens. Constellation runs the models in
PyTorch, reading them from the installed jar; it never ships them.

This snapshot records, for each JChronologer version, the SHA-256 of the
jar and of every model member, by role. Constellation's tokenizer and
decoders were checked against these files (the jar's own preprocessing
code and predictions), so a member whose hash is not in the snapshot is
refused rather than run on assumptions. A new JChronologer means running
this script on it, then the tokenizer survey
(``scripts/survey-jchronologer-tokens.py``) and the tests.

With ``--test-data`` the preprocessing files the tokenizer reads are
also copied to ``tests/data/jchronologer/<version>/`` (Apache-2.0,
credited in ``NOTICE.md``), so CI tests the tokenizer without the jar.

Run from project root:
    python3 scripts/build-jchronologer-models-json.py [--jar PATH] [--test-data]

Without ``--jar`` the jar is the one the installed EncyclopeDIA's
manifest ``Class-Path`` names.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import zipfile
from importlib import resources
from pathlib import Path

SNAPSHOT_NAME = "jchronologer_models.json"
POM_PROPERTIES = "META-INF/maven/org.searlelab/jchronologer/pom.properties"
TEST_DATA = Path("tests/data/jchronologer")
#: The roles the tokenizer reads preprocessing files for.
TOKENIZED_ROLES = ("chronologer", "cartographer", "electrician", "sculptor")


def _default_jar() -> Path:
    from constellation.thirdparty.encyclopedia import jchronologer_jar
    from constellation.thirdparty.registry import find

    return jchronologer_jar(find("encyclopedia").path)


def _version(archive: zipfile.ZipFile) -> str:
    for line in archive.read(POM_PROPERTIES).decode("utf-8").splitlines():
        key, _, value = line.partition("=")
        if key.strip() == "version":
            return value.strip()
    raise SystemExit(f"no version in {POM_PROPERTIES}")


def describe(jar: Path) -> tuple[str, dict, dict[str, bytes]]:
    """(version, snapshot entry, preprocessing bytes by role) of one jar."""
    with zipfile.ZipFile(jar) as archive:
        version = _version(archive)
        models: dict[str, dict] = {}
        preprocessing: dict[str, bytes] = {}
        for name in sorted(archive.namelist()):
            if not name.startswith("models/") or not name.endswith(".torchscript.pt"):
                continue
            stem = name[len("models/") : -len(".torchscript.pt")]
            role = stem.split("_", 1)[0].lower()
            if role in models:
                raise SystemExit(f"two {role} models in {jar}: {models[role]['stem']} and {stem}")
            pre_name = f"models/{stem}.preprocessing.json"
            pre = archive.read(pre_name)
            models[role] = {
                "stem": stem,
                "model_member": name,
                "model_sha256": hashlib.sha256(archive.read(name)).hexdigest(),
                "preprocessing_member": pre_name,
                "preprocessing_sha256": hashlib.sha256(pre).hexdigest(),
            }
            preprocessing[role] = pre
    entry = {
        "jar_name": jar.name,
        "jar_sha256": hashlib.sha256(jar.read_bytes()).hexdigest(),
        "models": models,
    }
    return version, entry, preprocessing


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--jar", type=Path, default=None)
    parser.add_argument("--test-data", action="store_true",
                        help=f"copy the tokenizer's preprocessing files to {TEST_DATA}/<version>/")
    args = parser.parse_args()

    jar = args.jar or _default_jar()
    version, entry, preprocessing = describe(jar)

    out = Path(str(resources.files("constellation.data"))) / SNAPSHOT_NAME
    snapshot = json.loads(out.read_text()) if out.exists() else {}
    snapshot["comment"] = (
        "Generated by scripts/build-jchronologer-models-json.py from installed JChronologer jars; "
        "do not edit. SHA-256 of each jar and model member Constellation was checked against."
    )
    snapshot.setdefault("versions", {})[version] = entry
    snapshot["versions"] = dict(sorted(snapshot["versions"].items()))
    out.write_text(json.dumps(snapshot, indent=1, sort_keys=True) + "\n")
    print(f"wrote {out}: JChronologer {version} ({', '.join(entry['models'])})")

    if args.test_data:
        dest = TEST_DATA / version
        dest.mkdir(parents=True, exist_ok=True)
        for role in TOKENIZED_ROLES:
            target = dest / Path(entry["models"][role]["preprocessing_member"]).name
            target.write_bytes(preprocessing[role])
            print(f"copied {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
